<?php

// Writes a throwaway config/brand.php for a CI run, as an app commits its own brand: well-formed values worth nothing, so a production-mode job (Deploy order, Production
// rehearsal) gets past the brand-placeholder checks in /up and kit:preflight without the deprecated KIT_BRAND_* env (removed in tey/kit 0.17).
//
//   php bin/ci-brand-config.php [--force] [--path=FILE] [--bare] [key=value ...]
//
// By default it overwrites the committed config/brand.php (the template's placeholders), so it does that only in CI (CI=true) or with --force; never commit what it
// writes. --path=FILE writes elsewhere instead (a test's throwaway app root) and needs neither. key=value sets or overrides a brand key; 'true'/'false' become
// booleans, and a value starting with { or [ is JSON (presets). --bare starts from no keys instead of the throwaway brand below.

$args = array_slice($argv, 1);
$path = null;
foreach ($args as $arg) {
    if (str_starts_with($arg, '--path=')) {
        $path = substr($arg, 7);
    }
}
if ($path === null && getenv('CI') !== 'true' && ! in_array('--force', $args, true)) {
    fwrite(STDERR, "bin/ci-brand-config.php overwrites config/brand.php: it runs only in CI, or with --force.\n");
    exit(1);
}

$brand = [
    'logomark' => '/favicon.svg',
    'accent' => '#0f766e',
    'hello_email' => 'hello@ci.test',
    'support_email' => 'support@ci.test',
    'privacy_email' => 'privacy@ci.test',
    'mail_from_address' => 'updates@ci.test',
];
if (in_array('--bare', $args, true)) {
    $brand = [];
}
foreach ($args as $arg) {
    if (str_contains($arg, '=') && ! str_starts_with($arg, '--')) {
        [$key, $value] = explode('=', $arg, 2);
        $brand[$key] = match ($value) {
            'true' => true,
            'false' => false,
            default => str_starts_with($value, '{') || str_starts_with($value, '[') ? json_decode($value, true, flags: JSON_THROW_ON_ERROR) : $value,
        };
    }
}

$file = $path ?? dirname(__DIR__).'/config/brand.php';
file_put_contents($file, "<?php\n\n// Generated by bin/ci-brand-config.php for this CI run only. Not committed.\nreturn ".var_export($brand, true).";\n");
echo ($path ?? 'config/brand.php').': '.implode(', ', array_keys($brand))."\n";
